import Foundation

/// Interface language. English is the base; Chinese follows the system language
/// unless CROW_UI_LANGUAGE ("en", "zh" or empty for automatic) says otherwise.
/// Read once at launch: changing it takes effect after a restart.
enum CrowUILanguage {
    static let isChinese: Bool = {
        let setting = (CrowEnvironment.value("CROW_UI_LANGUAGE") ?? "")
            .trimmingCharacters(in: .whitespacesAndNewlines)
            .lowercased()
        if setting.hasPrefix("zh") { return true }
        if setting.hasPrefix("en") { return false }
        return Locale.preferredLanguages.first?.lowercased().hasPrefix("zh") ?? false
    }()
}

/// Localizes an English interface string. Unknown strings stay English.
func L(_ english: String) -> String {
    guard CrowUILanguage.isChinese else { return english }
    return chineseStrings[english] ?? english
}

